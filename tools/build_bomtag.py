"""Build tools/lisp/bomtag.lsp = Part Master v3 data (126 parts, names -> keywords, default material codes) + material codes + bomtag_core.lsp. Run again when the part list changes."""
import json, os, re
R = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
pm = json.load(open(os.path.join(R, "data", "part_master_v3.json"), encoding="utf-8")); parts = pm["parts"] if isinstance(pm, dict) else pm
q = lambda s: '"' + str(s).replace("\\", "/").replace('"', "'") + '"'
mats = ["A", "A1"] + [f"{f}-{t}-{v}" for f in "BC" for t in (6, 9, 12, 15, 18, 25) for v in ("0X", "1X", "2X")] + ["MT-20x20", "MT-25x50", "MT-40x60", "MT-50x50", "MT-40x80", "D1", "D2"]


def pmcode(c):
    """Part Master default_mat_code ('C18 1X', 'B12 0X', 'A (A-25 in 9 Okt)') -> BOM-APP/factory code ('C-18-1X', 'B-12-0X', 'A')"""
    c = (c or "").strip()
    m = re.match(r"^([BC])\s*-?(\d+)\s*-?\s*([012]X)", c)
    if m: return f"{m.group(1)}-{m.group(2)}-{m.group(3)}"
    m = re.match(r"^(A1|A)\b", c)
    return m.group(1) if m else ""


BAD = set("*?#@.~`,[]'\"\\|;")
kw = {}
for p in sorted(parts, key=lambda p: p["part_no"]):
    for w in [p["name"]] + [a.strip() for a in (p.get("also_called") or "").split(";")]:
        w = w.strip().upper()
        if len(w) >= 4 and not (set(w) & BAD) and "(" not in w and w not in kw: kw[w] = p["part_no"]
kw.update({"PERMANENT SHELF": "308", "ADJUSTABLE SHELF": "309", "DOOR STILE": "502", "DOOR RAIL": "503"})

pmx = " ".join(f"({q(p['part_no'])} {q(p['name'])} {q(pmcode(p.get('default_mat_code')))})" for p in parts)
kwx = " ".join(f"({q(k)} {q(v)})" for k, v in sorted(kw.items()))
prx = " ".join(f"({q(p['part_no'])} {q(p['name'])})" for p in parts)
matx = " ".join(q(m) for m in mats)
data = f"(setq *bt-pm* '({pmx}))\n(setq *bt-kw* '({kwx}))\n(setq *bt-parts* '({prx}))\n(setq *bt-mats* '({matx}))\n"
core = open(os.path.join(R, "tools", "lisp", "bomtag_core.lsp"), encoding="utf-8").read()
text = ";;; GENERATED by tools/build_bomtag.py - do not edit; edit bomtag_core.lsp\n" + data + core
open(os.path.join(R, "tools", "lisp", "bomtag.lsp"), "wb").write(text.encode("ascii", "replace").replace(b"\r\n", b"\n").replace(b"\n", b"\r\n"))
print("bomtag.lsp:", len(parts), "parts,", len(kw), "keywords,", len(mats), "material codes")


def balance(s):
    depth = 0; ins = False; i = 0; line = 1; bad = []
    while i < len(s):
        c = s[i]
        if ins:
            if c == "\\": i += 1
            elif c == '"': ins = False
        elif c == '"': ins = True
        elif c == ";":
            while i < len(s) and s[i] != "\n": i += 1
            continue
        elif c == "(": depth += 1
        elif c == ")":
            depth -= 1
            if depth < 0: bad.append(line); depth = 0
        if c == "\n": line += 1
        i += 1
    return depth, bad


print("paren balance (0 = ok):", balance(text))
