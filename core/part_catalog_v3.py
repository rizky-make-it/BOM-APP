def get_part(part_no: Union[int, str]) -> Optional[Dict[str, Any]]:
    """Retrieve part definition by 3-digit part number."""
    try:
        val = int(str(part_no).strip())
        return PART_CATALOG_V3.get(val)
    except (ValueError, TypeError):
        return None

def find_parts_by_family(family_id: int) -> List[Dict[str, Any]]:
    """Retrieve all parts belonging to a family (1-9)."""
    return [p for p in PART_CATALOG_V3.values() if p["family_id"] == family_id]

def find_part_by_name(name_query: str) -> Optional[Dict[str, Any]]:
    """Search part by standard name or alias (case-insensitive)."""
    q = name_query.strip().lower()
    for p in PART_CATALOG_V3.values():
        if p["name"].lower() == q:
            return p
        if q in [a.strip().lower() for a in p["also_called"].split(";")]:
            return p
    for p in PART_CATALOG_V3.values():
        if q in p["name"].lower():
            return p
    return None
