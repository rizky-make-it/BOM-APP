def format_part_label(part_no: Union[int, str], mat_code: str = "") -> str:
    """
    Format standard BOM label: [PART_NO] [MAT_CODE]
    Example: 401 A-20-0X, 402 B-12-0X, 901 DTC-14
    """
    p_str = str(part_no).strip()
    m_str = str(mat_code).strip()
    if not m_str:
        return p_str
    # Avoid duplicate prefix if already included
    if m_str.startswith(p_str + " ") or m_str.startswith(p_str + "/"):
        return m_str
    return f"{p_str} {m_str}"

def map_legacy_to_v3(old_id: Union[int, str]) -> Optional[int]:
    """
    Map legacy number (1-25 or circled unicode ①-⑰) to new 3-digit number.
    """
    if isinstance(old_id, int) and old_id in OLD_9OKT_TO_V3:
        return OLD_9OKT_TO_V3[old_id]
    s = str(old_id).strip()
    if s in OLD_13OKT_TO_V3:
        return OLD_13OKT_TO_V3[s]
    if s.isdigit() and int(s) in OLD_9OKT_TO_V3:
        return OLD_9OKT_TO_V3[int(s)]
    return None

